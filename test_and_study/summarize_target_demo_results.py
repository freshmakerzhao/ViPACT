#!/usr/bin/env python3
"""
Summarize target-switch demo results generated by demo_grasp_target_by_id.py.

Example:
  conda run -n act3_env python test_and_study/summarize_target_demo_results.py \
    --input-dir notes/target_demo_26041508_eval
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Dict, List


def _safe_int(v, default: int = -1) -> int:
    try:
        return int(v)
    except Exception:
        return default


def _safe_float(v, default: float = 0.0) -> float:
    try:
        return float(v)
    except Exception:
        return default


def _load_records(input_dirs: List[Path], pattern: str) -> List[Dict]:
    files: List[Path] = []
    for d in input_dirs:
        files.extend(sorted(d.glob(pattern)))

    records: List[Dict] = []
    for fp in files:
        try:
            data = json.loads(fp.read_text(encoding="utf-8"))
        except Exception as e:
            print(f"[WARN] Skip invalid json: {fp} ({e})")
            continue

        target_geom = data.get("target_geom", "")
        guessed_geom = data.get("guessed_grab_geom", "")
        target_lifted = bool(data.get("target_lifted", False))
        guessed_match = guessed_geom == target_geom and target_geom != ""
        strict_success = target_lifted and guessed_match

        rec = {
            "file": str(fp),
            "seed": _safe_int(data.get("seed"), -1),
            "target_id": _safe_int(data.get("target_id"), -1),
            "target_geom": target_geom,
            "guessed_grab_geom": guessed_geom,
            "target_lifted": target_lifted,
            "lifted_any": bool(data.get("lifted_any", False)),
            "guessed_match": guessed_match,
            "strict_success": strict_success,
            "episode_return": _safe_float(data.get("episode_return"), 0.0),
        }
        records.append(rec)

    return records


def _rate(numer: int, denom: int) -> float:
    if denom <= 0:
        return 0.0
    return numer / denom


def _summarize_group(records: List[Dict], key: str) -> Dict[str, Dict]:
    stats: Dict[str, Dict] = {}
    for r in records:
        g = str(r.get(key, "unknown"))
        if g not in stats:
            stats[g] = {
                "count": 0,
                "strict_success": 0,
                "target_lifted": 0,
                "avg_return_sum": 0.0,
            }
        stats[g]["count"] += 1
        stats[g]["strict_success"] += int(bool(r["strict_success"]))
        stats[g]["target_lifted"] += int(bool(r["target_lifted"]))
        stats[g]["avg_return_sum"] += float(r["episode_return"])

    for _, s in stats.items():
        c = s["count"]
        s["strict_success_rate"] = _rate(s["strict_success"], c)
        s["target_lifted_rate"] = _rate(s["target_lifted"], c)
        s["avg_return"] = s["avg_return_sum"] / c if c else 0.0
        del s["avg_return_sum"]
    return stats


def _print_group(title: str, stats: Dict[str, Dict]) -> None:
    print(f"\n{title}")
    print("-" * len(title))
    keys = sorted(stats.keys(), key=lambda x: _safe_int(x, 10**9))
    for k in keys:
        s = stats[k]
        print(
            f"{k:>6} | n={s['count']:>3} | strict={s['strict_success']:>3} "
            f"({100.0*s['strict_success_rate']:.1f}%) | lifted={s['target_lifted']:>3} "
            f"({100.0*s['target_lifted_rate']:.1f}%) | avg_return={s['avg_return']:.2f}"
        )


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--input-dir",
        action="append",
        required=True,
        help="Directory containing summary_target_*.json (repeatable)",
    )
    parser.add_argument(
        "--pattern",
        default="summary_target_*.json",
        help="Glob pattern for summary files",
    )
    parser.add_argument(
        "--save-json",
        default="",
        help="Optional path to save aggregate report json",
    )
    args = parser.parse_args()

    input_dirs = [Path(p).expanduser().resolve() for p in args.input_dir]
    for d in input_dirs:
        if not d.exists():
            raise FileNotFoundError(f"Input dir not found: {d}")

    records = _load_records(input_dirs, args.pattern)
    if not records:
        print("No summary files found.")
        return

    total = len(records)
    strict = sum(int(r["strict_success"]) for r in records)
    lifted = sum(int(r["target_lifted"]) for r in records)
    avg_ret = sum(float(r["episode_return"]) for r in records) / total

    print("Overall")
    print("-------")
    print(f"files={total}")
    print(f"strict_success={strict}/{total} ({100.0*_rate(strict, total):.1f}%)")
    print(f"target_lifted={lifted}/{total} ({100.0*_rate(lifted, total):.1f}%)")
    print(f"avg_return={avg_ret:.2f}")

    by_target = _summarize_group(records, "target_id")
    by_seed = _summarize_group(records, "seed")
    _print_group("By Target ID", by_target)
    _print_group("By Seed", by_seed)

    if args.save_json:
        out_path = Path(args.save_json).expanduser().resolve()
        out_path.parent.mkdir(parents=True, exist_ok=True)
        report = {
            "inputs": [str(d) for d in input_dirs],
            "pattern": args.pattern,
            "overall": {
                "count": total,
                "strict_success": strict,
                "strict_success_rate": _rate(strict, total),
                "target_lifted": lifted,
                "target_lifted_rate": _rate(lifted, total),
                "avg_return": avg_ret,
            },
            "by_target_id": by_target,
            "by_seed": by_seed,
        }
        out_path.write_text(json.dumps(report, indent=2), encoding="utf-8")
        print(f"\nSaved report: {out_path}")


if __name__ == "__main__":
    main()
